/**
 * Retorna los códigos ordenados: prioritarios primero, luego alfabético.
 */
export function getSortedCountryCodes(): CountryCode[] {
  return [...countryCodes].sort((a, b) => {
    if (a.priority !== b.priority) return a.priority - b.priority;
    return a.name.localeCompare(b.name);
  });
}

/**
 * Busca códigos por nombre o código de país.
 */
export function searchCountryCodes(query: string): CountryCode[] {
  const q = query.toLowerCase();
  return getSortedCountryCodes().filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q) ||
      c.dial.includes(q)
  );
}
